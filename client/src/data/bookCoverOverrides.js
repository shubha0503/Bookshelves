export function getBookCoverOverride(title) {
  const normalize = value => String(value || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  const key = Object.keys(BOOK_COVER_OVERRIDES).find(candidate => normalize(candidate) === normalize(title));
  return key ? BOOK_COVER_OVERRIDES[key].trim() : '';
}
